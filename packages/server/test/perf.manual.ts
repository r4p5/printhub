import { boot, form, setupShop } from './helpers.ts';
import { PDFDocument, StandardFonts } from 'pdf-lib';
const mb = () => Math.round(process.memoryUsage().rss / 1048576);
const { app, call, admin } = await boot();
await setupShop(app, admin);
console.log('idle rss MB', mb());
const doc = await PDFDocument.create(); const f = await doc.embedFont(StandardFonts.Helvetica);
for (let i = 0; i < 300; i++) doc.addPage([595, 842]).drawText('Page ' + (i + 1) + ' '.repeat(10) + 'x'.repeat(2000), { x: 20, y: 400, size: 6, font: f });
const bytes = await doc.save();
console.log('pdf KB', Math.round(bytes.length / 1024));
const c = (await call('POST', '/api/jobs', {})).body; const H = { 'x-job-token': c.token };
let t = Date.now();
const up = await call('POST', `/api/jobs/${c.job.id}/files`, form(bytes, 'big.pdf'), H);
console.log('upload+inspect ms', Date.now() - t, 'pages', up.body.document?.pages, 'rss', mb());
await call('POST', `/api/jobs/${c.job.id}/estimate`, { documents: [{ id: up.body.document.id, options: { pagesPerSheet: 4, sides: 'double' } }] }, H);
await call('POST', `/api/jobs/${c.job.id}/checkout`, {}, H);
t = Date.now();
await admin('POST', `/api/admin/jobs/${c.job.id}/verify-payment`, {});
while ((await admin('GET', `/api/admin/jobs/${c.job.id}`)).body.state !== 'completed') await new Promise(r => setTimeout(r, 50));
console.log('render+print ms', Date.now() - t, 'rss', mb());
await new Promise(r => setTimeout(r, 31_000));
global.gc?.();
console.log('after worker idle-exit rss', mb());
await app.close();
